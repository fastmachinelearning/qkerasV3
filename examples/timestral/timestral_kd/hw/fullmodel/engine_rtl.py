"""Verilog of the Timestral engine (``isa.Image`` -> ``engine.v`` + memory images).

Ports of ``timestral_engine``::

    clk, rst                 clock, synchronous reset
    start  (in)              pulse: run the program once (one variate)
    busy   (out)             high while running
    done   (out)             high once the last run finished (cleared by start)
    host_we, host_addr,      RAM access while idle: write the input window at XIN_BASE,
    host_wdata, host_rdata   read the head_post codes at OUT_BASE (host_rdata one cycle after addr)

Memories (initialised with ``$readmemh``, all synchronous-read so yosys maps them to block RAM):
``irom.mem`` (24 32-bit words per instruction), ``wrom.mem``, ``crom.mem``, ``lrom.mem``.

The datapath executes one multiply-accumulate step in three cycles (read, multiply, accumulate);
the epilogue rounds (half even / half up / constant division), applies relu / clip / a table and
writes the RAM.  Bit-exactness against ``isa.simulate`` is checked with Verilator (``verify``).
"""

from __future__ import annotations

import json
import os

from .isa import CROM, IMM, MAX, RAM, RHU, WROM, Image, Instr

NFIELD = 24


def _bits_u(n: int) -> int:
    return max(1, int(n - 1).bit_length())


def _sbits(lo: int, hi: int) -> int:
    return int(max(abs(int(lo)), abs(int(hi)) + 1)).bit_length() + 1


def encode(i: Instr) -> list[int]:
    space = {RAM: 0, WROM: 1, CROM: 2, IMM: 2}
    init_mode = 0 if i.init is None else (2 if i.init.space == RAM else 3)
    if i.init is None and i.op == MAX:
        init_mode = 1
    flags = (i.op & 1) | (i.tri_c << 1) | (i.tri_k << 2) | (init_mode << 3) | (i.init_neg << 5) | \
        ((i.rnd == RHU) << 6) | (i.relu << 7) | ((i.clip is not None) << 8) | ((i.lut is not None) << 9) | \
        ((i.div != 1) << 10) | (space[i.a.space] << 11) | (space[i.b.space] << 13)
    ini = i.init or i.a
    clip = i.clip or (0, 0)
    lut = i.lut or (0, 0)
    w = [i.R, i.C, i.K, flags, i.a.base, i.a.sr, i.a.sc, i.a.sk, i.b.base, i.b.sr, i.b.sc, i.b.sk,
         i.out.base, i.out.sr, i.out.sc, ini.base, ini.sr, ini.sc, i.shift, i.div, clip[0], clip[1], lut[0], lut[1]]
    for name, v in zip(("R", "C", "K", "flags", "a.base", "a.sr", "a.sc", "a.sk", "b.base", "b.sr", "b.sc", "b.sk",
                        "out.base", "out.sr", "out.sc", "init.base", "init.sr", "init.sc", "shift", "div", "clip_lo",
                        "clip_hi", "lut_base", "lut_off"), w):
        if not -(1 << 31) <= v < (1 << 31):
            raise ValueError(f"{i.note}: field {name} = {v} does not fit 32 bits")
    if not 0 <= i.shift <= 47 and not -31 <= i.shift <= 0:
        raise ValueError(f"{i.note}: shift {i.shift} outside the shifter range")
    return [v & 0xFFFFFFFF for v in w]


def _hex(path, values, width):
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    with open(path, "w") as f:
        for v in values:
            f.write(f"{int(v) & mask:0{digits}x}\n")


def write(img: Image, outdir: str, a_w: int = 32, b_w: int = 25, acc_w: int = 48) -> dict:
    """Write ``engine.v`` + ``*.mem`` + ``engine.json`` (geometry for the host / firmware)."""
    os.makedirs(outdir, exist_ok=True)
    words = [w for i in img.instrs for w in encode(i)] + [0] * NFIELD          # R = 0: halt
    p = dict(
        RAM_N=img.ram_words, RAM_AW=_bits_u(img.ram_words), RAM_W=32,
        W_N=max(len(img.wrom), 1), W_AW=_bits_u(max(len(img.wrom), 2)),
        W_W=max(_sbits(img.wrom.min(), img.wrom.max()), 2),
        C_N=max(len(img.crom), 1), C_AW=_bits_u(max(len(img.crom), 2)),
        C_W=max(_sbits(img.crom.min(), img.crom.max()), 2),
        L_N=max(len(img.lrom), 1), L_AW=_bits_u(max(len(img.lrom), 2)),
        L_W=max(_sbits(img.lrom.min(), img.lrom.max()), 2),
        I_N=len(words), I_AW=_bits_u(len(words)), A_W=a_w, B_W=b_w, ACC_W=acc_w,
        XIN_BASE=img.xin, OUT_BASE=img.out, IN_LEN=img.in_len, OUT_LEN=img.out_len, N_INSTR=len(img.instrs))
    _hex(os.path.join(outdir, "irom.mem"), words, 32)
    _hex(os.path.join(outdir, "wrom.mem"), img.wrom, p["W_W"])
    _hex(os.path.join(outdir, "crom.mem"), img.crom, p["C_W"])
    _hex(os.path.join(outdir, "lrom.mem"), img.lrom, p["L_W"])
    with open(os.path.join(outdir, "engine.v"), "w") as f:
        f.write(VERILOG.format(**p))
    with open(os.path.join(outdir, "engine.json"), "w") as f:
        json.dump(p, f, indent=1)
    return p


VERILOG = r"""// Generated by timestral_kd.hw.fullmodel.engine_rtl -- do not edit.
`default_nettype none
module timestral_engine (
    input  wire clk,
    input  wire rst,
    input  wire start,
    output reg  busy,
    output reg  done,
    input  wire host_we,
    input  wire [{RAM_AW}-1:0] host_addr,
    input  wire [31:0] host_wdata,
    output wire [31:0] host_rdata
);
    localparam RAM_N = {RAM_N}, RAM_AW = {RAM_AW};
    localparam W_N = {W_N}, W_AW = {W_AW}, W_W = {W_W};
    localparam C_N = {C_N}, C_AW = {C_AW}, C_W = {C_W};
    localparam L_N = {L_N}, L_AW = {L_AW}, L_W = {L_W};
    localparam I_N = {I_N}, I_AW = {I_AW};
    localparam A_W = {A_W}, B_W = {B_W}, ACC_W = {ACC_W};

    // ------------------------------------------------------------------ memories
    reg [31:0] ram [0:RAM_N-1];
    reg [W_W-1:0] wrom [0:W_N-1];
    reg [C_W-1:0] crom [0:C_N-1];
    reg [L_W-1:0] lrom [0:L_N-1];
    reg [31:0] irom [0:I_N-1];
    initial begin
        $readmemh("wrom.mem", wrom);
        $readmemh("crom.mem", crom);
        $readmemh("lrom.mem", lrom);
        $readmemh("irom.mem", irom);
    end

    reg  [RAM_AW-1:0] pa_addr, pb_addr;
    reg  pa_we;
    reg  [31:0] pa_wdata;
    reg  [31:0] pa_q, pb_q;
    wire [RAM_AW-1:0] pa_addr_m = busy ? pa_addr : host_addr;
    wire pa_we_m = busy ? pa_we : host_we;
    wire [31:0] pa_wdata_m = busy ? pa_wdata : host_wdata;
    wire [RAM_AW-1:0] pb_addr_m = busy ? pb_addr : host_addr;
    always @(posedge clk) begin
        if (pa_we_m) ram[pa_addr_m] <= pa_wdata_m;
        pa_q <= ram[pa_addr_m];
    end
    always @(posedge clk) pb_q <= ram[pb_addr_m];
    assign host_rdata = pb_q;

    reg [W_AW-1:0] w_addr;  reg [W_W-1:0] w_q;  always @(posedge clk) w_q <= wrom[w_addr];
    reg [C_AW-1:0] c_addr;  reg [C_W-1:0] c_q;  always @(posedge clk) c_q <= crom[c_addr];
    reg [L_AW-1:0] l_addr;  reg [L_W-1:0] l_q;  always @(posedge clk) l_q <= lrom[l_addr];
    reg [I_AW-1:0] i_addr;  reg [31:0] i_q;     always @(posedge clk) i_q <= irom[i_addr];

    // ------------------------------------------------------------------ instruction register
    reg [31:0] f [0:23];
    wire [15:0] R = f[0][15:0], C = f[1][15:0], K = f[2][15:0];
    wire [31:0] fl = f[3];
    wire op_max = fl[0], tri_c = fl[1], tri_k = fl[2];
    wire [1:0] init_mode = fl[4:3];
    wire init_neg = fl[5], rnd_rhu = fl[6], relu_en = fl[7], clip_en = fl[8], lut_en = fl[9], div_en = fl[10];
    wire [1:0] a_sp = fl[12:11], b_sp = fl[14:13];
    wire signed [31:0] shift = f[18];
    wire [31:0] divisor = f[19];
    wire [ACC_W-1:0] dvs = {{{{(ACC_W-32){{1'b0}}}}, divisor}};
    wire signed [31:0] clip_lo = f[20], clip_hi = f[21];
    wire [31:0] lut_base = f[22];
    wire signed [31:0] lut_off = f[23];

    // ------------------------------------------------------------------ loop state
    reg [15:0] r, c, k;
    reg signed [31:0] a_row, a_rc, a_ad, b_row, b_rc, b_ad, o_row, o_ad, n_row, n_ad;
    wire [15:0] c_last = tri_c ? ((r < C - 1) ? r : C - 1) : C - 1;
    wire [15:0] k_lim = tri_k ? ((r + 1 < K) ? r + 1 : K) : K;    // number of k iterations

    reg signed [ACC_W-1:0] acc, prod, v;
    reg signed [A_W-1:0] av;
    reg signed [B_W-1:0] bv;

    // operand data after a read (selected by space)
    wire signed [A_W-1:0] a_data = (a_sp == 2'd0) ? $signed(pa_q[A_W-1:0]) :
                                   (a_sp == 2'd1) ? $signed({{{{(A_W-W_W){{w_q[W_W-1]}}}}, w_q}}) :
                                                    $signed({{{{(A_W-C_W){{c_q[C_W-1]}}}}, c_q}});
    wire signed [B_W-1:0] b_data = (b_sp == 2'd0) ? $signed(pb_q[B_W-1:0]) :
                                   (b_sp == 2'd1) ? $signed({{{{(B_W-W_W){{w_q[W_W-1]}}}}, w_q}}) :
                                                    $signed({{{{(B_W-C_W){{c_q[C_W-1]}}}}, c_q}});
    wire signed [ACC_W-1:0] init_data = (init_mode == 2'd2) ? $signed({{{{(ACC_W-32){{pb_q[31]}}}}, pb_q}}) :
                                        $signed({{{{(ACC_W-C_W){{c_q[C_W-1]}}}}, c_q}});
    localparam signed [ACC_W-1:0] NEG_INF = $signed({{3'b111, {{(ACC_W-3){{1'b0}}}}}});   // -2^(ACC_W-3)

    // ------------------------------------------------------------------ rounding shifter
    wire [5:0] sh = shift[5:0];
    wire signed [ACC_W-1:0] q_sh = acc >>> sh;
    wire [ACC_W-1:0] mask = ({{ACC_W{{1'b1}}}} << sh);
    wire [ACC_W-1:0] rem = acc & ~mask;
    wire [ACC_W-1:0] half = ({{{{(ACC_W-1){{1'b0}}}}, 1'b1}} << (sh - 6'd1));
    wire round_up = rnd_rhu ? (rem >= half) : ((rem > half) || ((rem == half) && q_sh[0]));
    wire signed [ACC_W-1:0] shifted = (shift > 0) ? (q_sh + (round_up ? 1 : 0)) : (acc <<< (-shift));

    // ------------------------------------------------------------------ divider (floor, then half even)
    reg [ACC_W-1:0] d_num, d_q, d_rem;
    reg [6:0] d_cnt;
    reg d_neg;
    wire [ACC_W:0] d_try = {{d_rem[ACC_W-1:0], d_num[ACC_W-1]}};

    // ------------------------------------------------------------------ fsm
    localparam S_IDLE = 4'd0, S_FETCH = 4'd1, S_FETCHW = 4'd2, S_ELEM = 4'd3, S_INITW = 4'd4, S_RD = 4'd5,
               S_RDW = 4'd6, S_ACC = 4'd7, S_EPI = 4'd8, S_DIV = 4'd9, S_DIVR = 4'd10, S_POST = 4'd11,
               S_LUTW = 4'd12, S_WR = 4'd13, S_NEXT = 4'd14, S_DECODE = 4'd15;
    reg [3:0] st;
    reg [4:0] fi;
    reg [I_AW-1:0] pc;

    always @(posedge clk) begin
        pa_we <= 1'b0;
        if (rst) begin
            st <= S_IDLE; busy <= 1'b0; done <= 1'b0;
        end else case (st)
        S_IDLE: if (start) begin
            busy <= 1'b1; done <= 1'b0; pc <= 0; st <= S_FETCH;
        end
        S_FETCH: begin           // issue the 24 field reads
            i_addr <= pc; fi <= 0; st <= S_FETCHW;
        end
        S_FETCHW: begin
            if (fi != 0) f[fi - 1] <= i_q;
            if (fi == 5'd24) begin
                st <= S_DECODE; pc <= pc + 24;
            end else begin
                i_addr <= pc + fi + 1; fi <= fi + 1;
            end
        end
        S_DECODE: begin
            if (R == 0) begin
                busy <= 1'b0; done <= 1'b1; st <= S_IDLE;
            end else begin
                r <= 0; c <= 0;
                a_row <= f[4]; a_rc <= f[4];  b_row <= f[8]; b_rc <= f[8];
                o_row <= f[12]; o_ad <= f[12]; n_row <= f[15]; n_ad <= f[15];
                st <= S_ELEM;
            end
        end
        S_ELEM: begin            // start one output element (r, c)
            pb_addr <= n_ad[RAM_AW-1:0]; c_addr <= n_ad[C_AW-1:0];
            k <= 0; a_ad <= a_rc; b_ad <= b_rc;
            st <= S_INITW;
        end
        S_INITW: st <= S_RD;     // init data valid next cycle (in S_RD)
        S_RD: begin
            if (k == 0) begin
                case (init_mode)
                    2'd0: acc <= 0;
                    2'd1: acc <= NEG_INF;
                    default: acc <= init_neg ? -init_data : init_data;
                endcase
            end
            if (k >= k_lim) st <= S_EPI;
            else begin
                pa_addr <= a_ad[RAM_AW-1:0]; pb_addr <= b_ad[RAM_AW-1:0];
                w_addr <= (a_sp == 2'd1) ? a_ad[W_AW-1:0] : b_ad[W_AW-1:0];
                c_addr <= (a_sp == 2'd2) ? a_ad[C_AW-1:0] : b_ad[C_AW-1:0];
                st <= S_RDW;
            end
        end
        S_RDW: st <= S_ACC;      // memory outputs valid in S_ACC
        S_ACC: begin
            if (op_max) acc <= ($signed(a_data) > acc) ? $signed(a_data) : acc;
            else acc <= acc + a_data * b_data;
            a_ad <= a_ad + $signed(f[7]); b_ad <= b_ad + $signed(f[11]);
            k <= k + 1;
            st <= S_RD;
        end
        S_EPI: begin
            if (div_en) begin
                d_neg <= acc[ACC_W-1];
                d_num <= acc[ACC_W-1] ? -acc : acc;
                d_rem <= 0; d_q <= 0; d_cnt <= 0;
                st <= S_DIV;
            end else begin
                v <= shifted; st <= S_POST;
            end
        end
        S_DIV: begin             // restoring division |acc| / divisor
            if (d_try >= {{1'b0, dvs}}) begin
                d_rem <= d_try - {{1'b0, dvs}}; d_q <= {{d_q[ACC_W-2:0], 1'b1}};
            end else begin
                d_rem <= d_try[ACC_W-1:0]; d_q <= {{d_q[ACC_W-2:0], 1'b0}};
            end
            d_num <= d_num << 1;
            d_cnt <= d_cnt + 1;
            if (d_cnt == ACC_W - 1) st <= S_DIVR;
        end
        S_DIVR: begin            // floor division of the signed value, then round half even
            begin : rnd_div
                reg [ACC_W-1:0] qf, rf;
                reg signed [ACC_W-1:0] qs;
                if (d_neg && d_rem != 0) begin qs = -$signed(d_q) - 1; rf = dvs - d_rem; end
                else begin qs = d_neg ? -$signed(d_q) : $signed(d_q); rf = d_rem; end
                if ((rf << 1) > dvs || ((rf << 1) == dvs && qs[0])) v <= qs + 1;
                else v <= qs;
            end
            st <= S_POST;
        end
        S_POST: begin
            begin : post
                reg signed [ACC_W-1:0] t;
                t = v;
                if (relu_en && t < 0) t = 0;
                if (clip_en) begin
                    if (t < clip_lo) t = clip_lo;
                    if (t > clip_hi) t = clip_hi;
                end
                v <= t;
                l_addr <= lut_base + t - lut_off;
            end
            st <= lut_en ? S_LUTW : S_WR;
        end
        S_LUTW: st <= S_WR;      // l_q valid in S_WR
        S_WR: begin
            pa_addr <= o_ad[RAM_AW-1:0];
            pa_wdata <= lut_en ? {{{{(32-L_W){{l_q[L_W-1]}}}}, l_q}} : v[31:0];
            pa_we <= 1'b1;
            st <= S_NEXT;
        end
        S_NEXT: begin            // advance (r, c)
            if (c < c_last) begin
                c <= c + 1;
                a_rc <= a_rc + $signed(f[6]); b_rc <= b_rc + $signed(f[10]);
                o_ad <= o_ad + $signed(f[14]); n_ad <= n_ad + $signed(f[17]);
                st <= S_ELEM;
            end else if (r + 1 < R) begin
                r <= r + 1; c <= 0;
                a_row <= a_row + $signed(f[5]); a_rc <= a_row + $signed(f[5]);
                b_row <= b_row + $signed(f[9]); b_rc <= b_row + $signed(f[9]);
                o_row <= o_row + $signed(f[13]); o_ad <= o_row + $signed(f[13]);
                n_row <= n_row + $signed(f[16]); n_ad <= n_row + $signed(f[16]);
                st <= S_ELEM;
            end else st <= S_FETCH;
        end
        default: st <= S_IDLE;
        endcase
    end
endmodule
`default_nettype wire
"""
